// Browser fixture: exercise production functions against the actual DOM.
async function runChatChecks() {
    const result = document.getElementById('test-results');
    const checks = [];
    function check(ok, name) {
        if (!ok) throw new Error(name);
        checks.push(name);
        result.textContent = checks.map(x => 'PASS: ' + x).join('\n');
    }
    try {
        window.newChatReady();
        check(!!chatContainer.querySelector('.empty-chat'), 'Schermata iniziale ripristinata');
        window.msgQueue.length = 0;
        messageInput.value = 'Messaggio di prova';
        sendMessage();
        messageInput.value = 'Doppio invio';
        sendMessage();
        check(window.msgQueue.length === 1 && messageInput.disabled, 'Doppio invio bloccato');
        check(!chatContainer.querySelector('.empty-chat'), 'Schermata iniziale rimossa al primo messaggio');
        check(document.getElementById('send-btn').hidden, 'Invio sostituito da Interrompi durante elaborazione');
        window.startStream(101);
        window.streamChunk('Dettagli di prova', true, 101);
        const details = chatContainer.querySelector('.reasoning-container');
        const header = details.querySelector('.reasoning-header');
        check(!details.classList.contains('open') && header.getAttribute('aria-expanded') === 'false', 'Dettagli chiusi durante lo streaming');
        toggleReasoning(header);
        check(details.classList.contains('open') && header.getAttribute('aria-expanded') === 'true', 'Dettagli apribili da pulsante accessibile');
        toggleReasoning(header);
        window.streamChunk('Prima frase disponibile. ', false, 101);
        await new Promise(resolve => setTimeout(resolve, 150));
        check(chatContainer.textContent.includes('Prima frase disponibile.'), 'Risposta visibile prima della fine del backend');
        check(!drainTimer && !isDraining, 'Nessun ciclo di rendering durante il silenzio del modello');
        window.streamChunk('Seconda frase. ', false, 101);
        window.streamChunk('Bozza provvisoria lunga', false, 101);
        window.endStream('**Risposta finale**', 101);
        check(chatContainer.textContent.includes('Risposta finale') && !chatContainer.textContent.includes('Bozza'), 'Testo finale autorevole');
        check(messageInput.disabled, 'Invio attende il rilascio del backend');
        window.turnFinished(101);
        check(!messageInput.disabled, 'Invio riabilitato dopo fine turno');
        window.streamChunk('TOKEN OBSOLETO', false, 101);
        check(!chatContainer.textContent.includes('TOKEN OBSOLETO'), 'Token tardivi ignorati');
        messageInput.value = 'Seconda richiesta';
        sendMessage();
        window.startStream(102);
        window.streamChunk('Risposta da annullare', false, 102);
        startNewChat();
        check(!document.getElementById('sidebar').classList.contains('active'), 'Nuova chat dalla testata non apre il menu');
        check(newChatPending && messageInput.disabled && chatContainer.textContent.includes('Messaggio di prova'), 'Nuova chat attende conferma');
        window.endStream('Risposta interrotta.', 102);
        window.turnFinished(102);
        check(messageInput.disabled, 'Nessun invio tra annullamento e nuova chat');
        window.newChatReady();
        window.streamChunk('VECCHIA CHAT', false, 102);
        await new Promise(resolve => setTimeout(resolve, 70));
        check(!chatContainer.textContent.includes('VECCHIA CHAT') && chatContainer.querySelectorAll('.message-wrapper').length === 0, 'Nuova chat pulita senza code residue');
        const target = document.createElement('div');
        renderSafeMarkdown(target, '<img src=x onerror="alert(1)"><script>alert(1)</script>[bad](javascript:alert(1)) **testo**');
        check(!target.querySelector('img,script,[onerror],a[href^="javascript:"]') && target.querySelector('strong'), 'Markdown privo di tag e link eseguibili');
        renderSafeMarkdown(target, '87.  \n29 × 3 = 87.');
        check(target.textContent.includes('87.') && !target.querySelector('ol'), 'Risposta numerica conservata senza lista vuota');
        renderSafeMarkdown(target, '3. Terzo punto\n4. Quarto punto');
        check(target.querySelector('ol').getAttribute('start') === '3', 'Numerazione originale delle liste conservata');
        messageInput.value = 'Verifica interruzione';
        sendMessage();
        window.startStream(103);
        window.cancelGeneration();
        check(JSON.parse(window.msgQueue.at(-1)).action === 'cancel_generation', 'Pulsante Interrompi invia il comando');
        window.endStream('Risposta interrotta.', 103);
        window.turnFinished(103);
        window.updateDiagnostics({resources: {cpu: null, ram: null, temp: null}, logs: []});
        check(document.getElementById('diag-temp-val').textContent === 'N/D' && document.getElementById('diag-cpu-val').textContent === 'N/D', 'Sensori mancanti mostrati come non disponibili');
        window.updateDiagnostics({resources: {cpu: 25, ram: 1200, temp: 37}, logs: [{time: '12:00', msg: '<img src=x onerror="alert(1)">'}]});
        check(document.getElementById('diag-temp-val').textContent === '37°C' && !document.getElementById('diag-logs').querySelector('img,[onerror]'), 'Diagnostica mostra valori ricevuti e log come testo');
        window.restoreDreamHistory([{text: '<img src=x onerror="alert(1)">', phase: 'hypothesis'}]);
        const journal = document.getElementById('dream-journal-entries');
        check(!journal.querySelector('img,[onerror]') && journal.textContent.includes('<img'), 'Ipotesi oniriche renderizzate come testo');
        for (let i = 0; i < 60; i++) window.handleDreamLog({text: 'Ipotesi ' + i, phase: 'hypothesis'});
        check(journal.children.length === 50, 'Diario limitato a 50 elementi');
        window.handleDreamLog({text: 'Ciclo completato', phase: 'done'});
        check(document.getElementById('dream-status-badge').textContent === 'Da verificare', 'Fine sogno distinta da conoscenza verificata');
        const hypothesis = {id: 'qa-dream', revision: 0, status: 'unverified',
            original_text: '<img src=x onerror="alert(1)"> Il mare aiuta a rilassarsi.',
            text: '<img src=x onerror="alert(1)"> Il mare aiuta a rilassarsi.', evidence: {text: 'Oggi sono stato al mare'}};
        window.restoreDreamReviews({items: [hypothesis], pending_count: 1});
        const reviewContainer = document.getElementById('dream-review-items');
        check(reviewContainer.textContent.includes('Da verificare') && !reviewContainer.querySelector('img,[onerror]'), 'Ipotesi da revisionare mostrate senza HTML eseguibile');
        reviewContainer.querySelector('.dream-review-actions button').click();
        let action = JSON.parse(window.msgQueue.at(-1));
        check(action.action === 'review_dream_hypothesis' && action.decision === 'confirm' && action.revision === 0 && action.id === 'qa-dream', 'Conferma inviata con identità e revisione originali');
        check([...reviewContainer.querySelectorAll('button')].every(button => button.disabled), 'Revisione attende la conferma del backend');
        const confirmed = {...hypothesis, revision: 1, status: 'user_confirmed'};
        window.dreamReviewResult({ok: true, reviewed_id: hypothesis.id, items: [confirmed]});
        check(reviewContainer.textContent.includes('Confermata da te') && document.getElementById('dream-review-notice').textContent.includes('salvata'), 'Conferma visualizzata soltanto dopo il salvataggio');
        reviewContainer.querySelectorAll('.dream-review-actions button')[1].click();
        let correction = reviewContainer.querySelector('textarea');
        correction.value = 'Il mare mi rilassa quando è tranquillo.';
        correction.dispatchEvent(new Event('input', {bubbles: true}));
        reviewContainer.querySelector('.dream-review-editor button').click();
        action = JSON.parse(window.msgQueue.at(-1));
        check(action.decision === 'correct' && action.correction === correction.value && action.revision === 1, 'Correzione inviata con testo esplicito');
        window.dreamReviewResult({ok: false, error: 'Salvataggio non riuscito', items: [confirmed]});
        check(reviewContainer.querySelector('textarea').value === 'Il mare mi rilassa quando è tranquillo.' && !reviewContainer.querySelector('.dream-review-editor').hidden, 'Errore di salvataggio conserva la correzione per riprovare');
        reviewContainer.querySelectorAll('.dream-review-actions button')[2].click();
        action = JSON.parse(window.msgQueue.at(-1));
        check(action.decision === 'reject' && action.revision === 1, 'Revoca inviata senza simulare un salvataggio');
        window.dreamReviewResult({ok: true, reviewed_id: hypothesis.id, items: [{...hypothesis, revision: 2, status: 'rejected'}]});
        check(!reviewContainer.querySelector('.dream-review-card') && document.getElementById('dream-review-notice').textContent.includes('scartata'), 'Scarta rimuove la scheda principale solo dopo il salvataggio');
        const archiveToggle = reviewContainer.querySelector('.dream-review-archive-toggle');
        check(archiveToggle.textContent === 'Mostra scartate (1)' && archiveToggle.getAttribute('aria-expanded') === 'false', 'Cronologia scartate disponibile senza cancellare le ipotesi');
        archiveToggle.click();
        check(reviewContainer.textContent.includes('esclusa dalle risposte') && reviewContainer.querySelector('.dream-review-card'), 'Archivio mostra la scheda scartata con stato esplicito');
        reviewContainer.querySelector('.dream-review-archive-toggle').click();
        window.restoreDreamReviews({items: [{...hypothesis, revision: 2, status: 'rejected'}]});
        check(!reviewContainer.querySelector('.dream-review-card'), 'Aggiornare il diario non fa ricomparire le scartate nascoste');
        window.restoreDreamReviews({items: [{...hypothesis, revision: 3, status: 'user_corrected',
            text: 'Una correzione 🌊', review_history: [{revision: 3, decision: 'correct',
                reviewed_at: '2026-10-06T12:00:00Z', text: '<script>alert(1)</script>', note: '<img src=x>'}]}]});
        check(reviewContainer.querySelector('.dream-review-actions button').textContent === 'Conferma l’originale', 'Riconferma dell’originale esplicita dopo correzione');
        check(!reviewContainer.querySelector('script,img') && reviewContainer.querySelector('details ul').textContent.includes('<script>'), 'Cronologia revisioni priva di HTML eseguibile');
        reviewContainer.querySelectorAll('.dream-review-actions button')[1].click();
        correction = reviewContainer.querySelector('textarea');
        correction.value = '   ';
        correction.dispatchEvent(new Event('input', {bubbles: true}));
        let queueBefore = window.msgQueue.length;
        reviewContainer.querySelector('.dream-review-editor button').click();
        check(window.msgQueue.length === queueBefore && !dreamReviewBusy, 'Correzione vuota non inviata al backend');
        correction.value = 'Il mare mi rilassa 🌊 — solo quando è tranquillo.';
        correction.dispatchEvent(new Event('input', {bubbles: true}));
        const note = reviewContainer.querySelectorAll('textarea')[1];
        note.value = 'Perché l’ho osservato ieri: "tranquillo".';
        note.dispatchEvent(new Event('input', {bubbles: true}));
        reviewContainer.querySelector('.dream-review-editor button').click();
        action = JSON.parse(window.msgQueue.at(-1));
        check(action.correction === correction.value && action.note === note.value && action.revision === 3, 'Unicode e nota conservati nel comando di revisione');
        queueBefore = window.msgQueue.length;
        sendDreamReview(hypothesis, 'reject');
        check(window.msgQueue.length === queueBefore, 'Seconda revisione bloccata mentre si attende il salvataggio');
        window.dreamReviewResult({ok: false, error: 'La revisione è cambiata',
            items: [{...hypothesis, revision: 4, status: 'user_confirmed'}]});
        check(reviewContainer.querySelectorAll('textarea')[1].value === note.value &&
            reviewContainer.querySelector('textarea').value === correction.value, 'Conflitto conserva testo e nota della bozza');
        reviewContainer.querySelector('.dream-review-editor button').click();
        check(JSON.parse(window.msgQueue.at(-1)).revision === 4, 'Riprova dopo conflitto usa la revisione aggiornata');
        window.dreamReviewResult({ok: true, reviewed_id: hypothesis.id, items: [{...hypothesis,
            revision: 5, status: 'user_corrected', text: correction.value}]});
        check(reviewContainer.querySelector('.dream-review-editor').hidden && !dreamReviewDrafts.has(hypothesis.id), 'Solo il salvataggio riuscito elimina la bozza');
        window.restoreDreamReviews({items: []});
        check(reviewContainer.textContent.includes('Nessuna ipotesi') && !reviewContainer.querySelector('button'), 'Archivio vuoto mostra uno stato esplicito senza azioni residue');
        check(!document.querySelector('.settings-advanced').open && document.getElementById('temp-cpu').closest('.settings-advanced'), 'Temperature disponibili nelle impostazioni avanzate chiuse');
        check(document.getElementById('dream-mode-toggle') && !document.getElementById('dream-mode-toggle').closest('.settings-advanced'), 'Attivazione sogni disponibile senza aprire i controlli avanzati');
        check(!document.querySelector('.dream-activity').open && document.getElementById('dream-journal-entries').closest('.dream-activity'), 'Registro tecnico separato e chiuso inizialmente');
        check(document.querySelector('.settings-advanced #voice-stack-status') && document.querySelector('.settings-advanced [onclick="startBenchmark()"]'), 'Motori e benchmark conservati nelle impostazioni avanzate');
        const ids = [...document.querySelectorAll('[id]')].map(element => element.id);
        check(new Set(ids).size === ids.length, 'Nessun ID duplicato dopo la riorganizzazione');
        window.restoreDreamReviews({items: [hypothesis]});
        check(document.getElementById('dream-review-count').textContent === '1 riflessione da valutare' && reviewContainer.querySelector('.dream-confirm-action'), 'Conteggio chiaro e azione Conferma evidenziata');
        check(!reviewContainer.querySelector('details').open && !document.querySelector('.dream-help').open, 'Provenienza e spiegazioni restano accessibili senza affollare le schede');
        window.openVoiceMode();
        check(document.getElementById('voice-overlay').classList.contains('voice-glass') && document.querySelector('.voice-answer-card'), 'Voce con schede separate per risposta e trascrizione');
        window.updateVoiceText('<img src=x onerror=alert(1)> Ciao ALLMA');
        check(document.getElementById('voice-text').textContent.includes('<img') && !document.getElementById('voice-text').querySelector('img'), 'Trascrizione vocale mostrata come testo sicuro');
        addMessage('**Ciao!** Sono ALLMA.', 'bot');
        check(document.getElementById('voice-answer').querySelector('strong') && document.getElementById('voice-answer').textContent.includes('Sono ALLMA'), 'Risposta della chat visibile anche nella scheda vocale');
        window.updateVoiceState({state:'thinking',message:'Sto elaborando…'});
        check(document.getElementById('voice-overlay').dataset.voiceState === 'thinking' && document.getElementById('voice-mic-btn').getAttribute('aria-label') === 'Interrompi', 'Stato elaborazione leggibile e comando di interruzione conservato');
        check(document.querySelector('#voice-overlay .voice-footer').textContent === 'Tocca per interrompere', 'Indicazione del microfono coerente con l’elaborazione');
        window.updateVoiceState({state:'listening'});
        check(document.getElementById('voice-status').textContent === 'Ti ascolto…' && document.querySelector('#voice-overlay .voice-footer').textContent.includes('terminare'), 'Ascolto distinguibile anche senza un messaggio del backend');
        const ring = document.querySelector('.voice-mic-ring');
        const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
        check(getComputedStyle(ring).animationName === (reducedMotion ? 'none' : 'allma-listening'), 'Animazione ascolto limitata allo stato attivo e alla preferenza movimento');
        window.updateVoiceState({state:'thinking'});
        check(getComputedStyle(ring,'::after').animationName === (reducedMotion ? 'none' : 'allma-wait'), 'Anello di elaborazione animato solo quando necessario');
        document.body.classList.add('motion-paused');
        check(getComputedStyle(ring,'::after').animationPlayState === 'paused', 'Animazioni sospese quando la pagina non è visibile');
        document.body.classList.remove('motion-paused');
        window.updateVoiceState({state:'idle'});
        check(getComputedStyle(ring).animationName === 'none', 'Nessun movimento continuo del microfono a riposo');
        check(document.querySelector('.boot-card h1').textContent.includes('pensare insieme'), 'Intro coerente presente anche durante l’apertura della chat');
        window.startStream(104);
        window.endStream('Risposta vocale finale.',104);
        window.turnFinished(104);
        check(document.getElementById('voice-answer').textContent.trim() === 'Risposta vocale finale.', 'Finale dello streaming riportato nella scheda vocale');
        window.endStream('Finale obsoleto',103);
        check(!document.getElementById('voice-answer').textContent.includes('obsoleto'), 'Finale obsoleto non sovrascrive la scheda vocale');
        window.closeVoiceMode();
        check(!document.getElementById('voice-overlay').classList.contains('active') && !VoiceFX.isActive(), 'Chiusura vocale disattiva gli effetti e il pannello');
        window.openVoiceMode();
        check(document.getElementById('voice-text').textContent === '' && document.getElementById('voice-answer').textContent.includes('Sono qui.'), 'Riapertura vocale pulita senza vecchie frasi');
        window.closeVoiceMode();
        for (const panelName of ['settings', 'memory', 'dream']) {
            window.openPanel(panelName);
            await new Promise(resolve => setTimeout(resolve, 260));
            const bounds = document.getElementById('panel-' + panelName).getBoundingClientRect();
            check(Math.abs(bounds.left + bounds.width / 2 - window.innerWidth / 2) < 1 &&
                Math.abs(bounds.top + bounds.height / 2 - window.innerHeight / 2) < 1,
                'Pannello ' + panelName + ' centrato dopo l’animazione');
            window.closePanel(panelName);
        }
        result.textContent += '\nTUTTI I CONTROLLI PASSATI';
    } catch (error) {
        result.textContent += '\nFAIL: ' + error.message;
        throw error;
    }
}
